const fs = require('node:fs');
const path = require('node:path');

function readEnvFile(file) {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match && !Object.hasOwn(process.env, match[1])) {
      process.env[match[1]] = match[2].replace(/^(["'])(.*)\1$/, '$2');
    }
  }
}

readEnvFile(path.resolve(__dirname, '..', '.env'));
const publicConfig = JSON.parse(fs.readFileSync(path.resolve(__dirname, '..', 'supabase', 'public-config.json'), 'utf8'));
const url = process.env.SUPABASE_URL || publicConfig.url;
const anonKey = process.env.SUPABASE_ANON_KEY || publicConfig.anonKey;
if (!url || !anonKey) {
  throw new Error('Set SUPABASE_URL and SUPABASE_ANON_KEY in .env or supabase/public-config.json.');
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(url)) {
  throw new Error('SUPABASE_URL must be a valid https://<project>.supabase.co URL.');
}
const isPublishableKey = /^sb_publishable_[A-Za-z0-9_-]+$/.test(anonKey);
const isLegacyJwtKey = /^eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(anonKey);
if (!isPublishableKey && !isLegacyJwtKey) {
  throw new Error('SUPABASE_ANON_KEY must be a Supabase publishable key (sb_publishable_…) or legacy anon key. A database password or secret key cannot be used by the website.');
}
if (isLegacyJwtKey) {
  try {
    const role = JSON.parse(Buffer.from(anonKey.split('.')[1], 'base64url').toString('utf8')).role;
    if (role === 'service_role') throw new Error('SUPABASE_ANON_KEY cannot be a service-role key. Use the public anon key.');
  } catch (error) {
    if (/service-role key/.test(error.message)) throw error;
  }
}
const output = `/* Generated by scripts/write-config.js. Supabase anon keys are public by design. */\nwindow.SUPABASE_CONFIG = ${JSON.stringify({ url, anonKey })};\n`;
const outputDirectory = path.resolve(__dirname, '..', 'dist');
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, 'config.js'), output);
console.log('Supabase browser config generated.');
