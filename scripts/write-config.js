const fs = require('node:fs');
const path = require('node:path');

function readEnvFile(file) {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match && !Object.hasOwn(process.env, match[1])) {
      process.env[match[1]] = match[2].replace(/^(["'])(.*)\1$/, '$2');
    }
  }
}

readEnvFile(path.resolve(__dirname, '..', '.env'));
const url = process.env.SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY;
if (!url || !anonKey) {
  throw new Error('SUPABASE_URL and SUPABASE_ANON_KEY are required. Set them in .env for local development or in your hosting provider environment variables.');
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/i.test(url)) {
  throw new Error('SUPABASE_URL must be a valid https://<project>.supabase.co URL.');
}
if (anonKey.length < 20) throw new Error('SUPABASE_ANON_KEY does not look like a valid Supabase public key.');
const output = `/* Generated by scripts/write-config.js. Supabase anon keys are public by design. */\nwindow.SUPABASE_CONFIG = ${JSON.stringify({ url, anonKey })};\n`;
const outputDirectory = path.resolve(__dirname, '..', 'dist');
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, 'config.js'), output);
console.log('Supabase browser config generated.');
